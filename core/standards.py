@dataclass(frozen=True)
class QdSpec:
    """杭先端の極限支持力度 qd の算定仕様。

    kind:
      "N"     : qd = coef × N(先端付近の平均N値)、cap で頭打ち
      "qu"    : qd = coef × qu(= 2c)、cap で頭打ち
      "steps" : N 値の区分ごとに一定値。steps は (N下限, qd) を降順に並べる。
                どの区分にも該当しない(N が最小の下限未満)場合は支持層の
                条件を満たさないものとしてエラーとする。
    """

